"""Weekly Feedback Report (.xlsx) built on the company's original report file.

Original week sheets are kept as-is (Q22); weeks after the last original sheet are generated by copying
the latest sheet and filling it. Cells are located by marker text, never by fixed row numbers."""
import io
import re
import sqlite3
from copy import copy
from dataclasses import dataclass, field
from datetime import date

import openpyxl
from openpyxl.styles import Font
from openpyxl.worksheet.worksheet import Worksheet

from . import config
from .logic import get_note, to_num
from .weeks import md_with_weekday, next_week, today_kst, week_monday, week_of, week_sunday, weeks_between

WEEK_SHEET = re.compile(r"^(\d{1,2})주$")
BLUE = "FF0000FF"
FIRST_COL, LAST_COL = 2, 10  # B..J
LINE_HEIGHT = 16.5


@dataclass
class TaskAt:
    """A task as it stood at the end of a report week."""
    no: int
    title: str
    category: str
    is_added: bool
    done: bool
    unit: str | None
    before_val: str | None
    after_val: str | None
    effect: str | None
    week_content: str | None


@dataclass
class Result:
    data: bytes
    filename: str
    sheets: list
    warnings: list = field(default_factory=list)


# ---------- worksheet helpers ----------

def _norm(s) -> str:
    return re.sub(r"\s+", "", str(s or ""))


def _find_row(ws: Worksheet, test, start: int = 1, stop: int | None = None) -> int | None:
    for r in range(start, (stop or ws.max_row) + 1):
        v = ws.cell(r, FIRST_COL).value
        if isinstance(v, str) and test(v.strip()):
            return r
    return None


def _merge_span(ws: Worksheet, row: int, col: int) -> int:
    for mr in ws.merged_cells.ranges:
        if mr.min_row == row and mr.min_col == col:
            return mr.max_row - mr.min_row + 1
    return 1


def _shift_rows(ws: Worksheet, idx: int, n: int) -> None:
    """Insert (n>0) or delete (n<0) rows at idx, keeping merges and row heights below in place."""
    moved = []
    for mr in list(ws.merged_cells.ranges):
        if mr.min_row >= idx:
            moved.append((mr.min_row, mr.min_col, mr.max_row, mr.max_col))
            ws.unmerge_cells(mr.coord)
    heights = {r: d.height for r, d in ws.row_dimensions.items() if r >= idx and d.height}
    if n > 0:
        ws.insert_rows(idx, n)
    else:
        ws.delete_rows(idx, -n)
    for r in list(heights):
        ws.row_dimensions[r].height = None
    for r, h in heights.items():
        if r + n >= idx:
            ws.row_dimensions[r + n].height = h
    for r1, c1, r2, c2 in moved:
        if n < 0 and r1 < idx - n:  # range inside the deleted rows
            continue
        ws.merge_cells(start_row=r1 + n, start_column=c1, end_row=r2 + n, end_column=c2)


def _clone_row_format(ws: Worksheet, src: int, dst: int) -> None:
    for c in range(1, ws.max_column + 1):
        ws.cell(dst, c)._style = copy(ws.cell(src, c)._style)
    if ws.row_dimensions[src].height:
        ws.row_dimensions[dst].height = ws.row_dimensions[src].height
    for mr in list(ws.merged_cells.ranges):
        if mr.min_row == mr.max_row == src:
            ws.merge_cells(start_row=dst, start_column=mr.min_col, end_row=dst, end_column=mr.max_col)


def _resize_rows(ws: Worksheet, first: int, have: int, need: int) -> None:
    """Make the data area starting at `first` exactly `need` rows long (format copied from its last row)."""
    if need > have:
        last = first + have - 1
        _shift_rows(ws, last + 1, need - have)
        for r in range(last + 1, first + need):
            _clone_row_format(ws, last, r)
    elif need < have:
        _shift_rows(ws, first + max(need, 1), -(have - max(need, 1)))
        if need == 0:
            for c in range(FIRST_COL, LAST_COL + 1):
                ws.cell(first, c).value = None


def _put(ws: Worksheet, row: int, col: int, value) -> None:
    cell = ws.cell(row, col)
    if type(cell).__name__ != "MergedCell":
        cell.value = value


def _num_or_text(v):
    n = to_num(v)
    if n is None:
        return v
    return int(n) if n == int(n) else n


def _set_lines_height(ws: Worksheet, row: int, text: str | None) -> None:
    lines = (text or "").count("\n") + 1
    ws.row_dimensions[row].height = max(LINE_HEIGHT * lines, 15)


# ---------- data ----------

def tasks_at(conn: sqlite3.Connection, company_id: int, year: int, week: int) -> list[TaskAt]:
    end = week_sunday(year, week)
    rows = conn.execute("SELECT * FROM tasks WHERE company_id=? ORDER BY no, id", (company_id,)).fetchall()
    out = []
    for t in rows:
        if date.fromisoformat(t["created_at"][:10]) > end:
            continue
        log = conn.execute("SELECT content FROM progress_logs WHERE task_id=? AND year=? AND week=?",
                           (t["id"], year, week)).fetchone()
        done = t["status"] == "완료" and (not t["done_date"] or date.fromisoformat(t["done_date"]) <= end)
        out.append(TaskAt(t["no"], t["title"], t["category"] or "기타", bool(t["is_added"]), done, t["unit"],
                          t["before_val"], t["after_val"], t["effect"], log["content"] if log else None))
    return out


# ---------- sections ----------

def _fill_title(ws, year, week):
    v = ws["B2"].value or ""
    text = re.sub(r"'\d{2}년", f"'{year % 100:02d}년", v)
    text = re.sub(r"\d+주차", f"{week}주차", text)
    ws["B2"].value = text if text != v or "주차" in v else f"'{year % 100:02d}년 {week}주차 컨설팅 Feedback Report"


def _fill_overview(ws, company):
    r = _find_row(ws, lambda v: v == "회사명")
    if not r:
        return
    fmt = lambda d: f"'{d[2:4]}.{d[5:7]}.{d[8:10]}" if d else ""
    _put(ws, r + 1, 2, company["name"])
    _put(ws, r + 1, 4, company["field"])
    _put(ws, r + 1, 6, company["consultant"])
    period = f"{fmt(company['start_date'])} ~  {fmt(company['end_date'])}" if company["start_date"] or company["end_date"] else None
    _put(ws, r + 1, 8, period)


def _blocks(ws, start, stop):
    return [r for r in range(start, stop) if ws.cell(r, FIRST_COL).value == "구분"]


def _fill_status_table(ws, tasks: list[TaskAt], base_template: bool):
    m1 = _find_row(ws, lambda v: v.startswith("□ 과제 추진현황"))
    m2 = _find_row(ws, lambda v: v.startswith("□ KPI"), start=(m1 or 1))
    if not m1 or not m2:
        return
    blocks = _blocks(ws, m1, m2)
    if not blocks:
        return
    block_h = 6
    # every block uses the category columns of the first block (right of 합계); the 협력사B sheet's
    # second block leaves C empty. Values are written as numbers: the originals' formulas miss cells.
    sum_col = next((c for c in range(3, LAST_COL + 1) if ws.cell(blocks[0], c).value == "합계"), 2)
    cat_cols = list(range(sum_col + 1, LAST_COL + 1))
    slots = [(b, c) for b in blocks for c in cat_cols]  # (block_row, col)
    template_cats = [str(ws.cell(b, c).value).strip() for b, c in slots if ws.cell(b, c).value]
    data_cats = list(dict.fromkeys(t.category for t in tasks))
    if base_template:
        cats = data_cats
    else:
        known = {_norm(c) for c in template_cats}
        cats = template_cats + [c for c in data_cats if _norm(c) not in known]

    # add blocks (copies of the last block, 8 slots each: C..J) while slots run short
    while len(slots) < len(cats):
        last = blocks[-1]
        new = last + block_h
        _shift_rows(ws, new, block_h)
        for i in range(block_h):
            _clone_row_format(ws, last + i, new + i)
            ws.cell(new + i, FIRST_COL).value = ws.cell(last + i, FIRST_COL).value
        blocks.append(new)
        slots += [(new, c) for c in cat_cols]
        m2 += block_h

    by_cat = {_norm(c): [] for c in cats}
    for t in tasks:
        by_cat.setdefault(_norm(t.category), []).append(t)

    def values(ts):
        total = len(ts)
        done = sum(t.done for t in ts)
        if not total:  # a template category with no tasks stays blank, as in the originals
            return dict.fromkeys(("총발굴건수", "발굴건수", "추가과제", "완료과제", "완료율", "진척율"))
        return {"총발굴건수": total, "발굴건수": sum(not t.is_added for t in ts),
                "추가과제": sum(t.is_added for t in ts), "완료과제": done,
                "완료율": done / total, "진척율": done / total}

    def write(block, col, vals):
        for i in range(1, block_h):
            label = str(ws.cell(block + i, FIRST_COL).value or "").strip()
            _put(ws, block + i, col, vals.get(label))

    if sum_col > 2:
        write(blocks[0], sum_col, values(tasks))
    for i, (b, c) in enumerate(slots):
        if i < len(cats):
            _put(ws, b, c, cats[i])
            write(b, c, values(by_cat[_norm(cats[i])]))
        else:
            for k in range(block_h):
                _put(ws, b + k, c, None)


def _kpi_area(ws):
    m = _find_row(ws, lambda v: v.startswith("□ KPI"))
    if not m:
        return None
    header = _find_row(ws, lambda v: v == "구분", start=m)
    first = header + 1
    r = first
    while ws.cell(r, FIRST_COL).value not in (None, "") or ws.cell(r, 3).value not in (None, ""):
        r += 1
    return header, first, r - first


def _fill_kpi(ws, company, tasks: list[TaskAt], warnings: list):
    area = _kpi_area(ws)
    if not area:
        warnings.append("템플릿에서 KPI 표를 찾지 못해 KPI 현황을 채우지 못했습니다")
        return
    header, first, have = area
    category_mode = company["kpi_mode"] == "category"

    # sample fonts for done / not-done rows, per column
    done_font, open_font = {}, {}
    for r in range(first, first + have):
        color = ws.cell(r, 3).font.color
        target = done_font if color is not None and color.rgb == BLUE else open_font
        if not target:
            target.update({c: copy(ws.cell(r, c).font) for c in range(FIRST_COL, LAST_COL + 1)})

    if category_mode:
        template_cats = [str(ws.cell(r, FIRST_COL).value).strip() for r in range(first, first + have)
                         if ws.cell(r, FIRST_COL).value]
        known = {_norm(c) for c in template_cats}
        cats = template_cats + list(dict.fromkeys(t.category for t in tasks if _norm(t.category) not in known))
        _resize_rows(ws, first, have, len(cats))
        ws.cell(header, 3).value = "과제수"
        for i, cat in enumerate(cats):
            r = first + i
            ts = [t for t in tasks if _norm(t.category) == _norm(cat)]
            monthly = [t for t in ts if _norm(t.unit) == "분/월"
                       and to_num(t.before_val) is not None and to_num(t.after_val) is not None]
            other = [t for t in ts if _norm(t.unit) != "분/월"
                     and to_num(t.before_val) is not None and to_num(t.after_val) is not None]
            before = sum(to_num(t.before_val) for t in monthly) if monthly else None
            after = sum(to_num(t.after_val) for t in monthly) if monthly else None
            note = []
            if monthly:
                note.append("분/월")
            if other:
                note.append(f"단위 상이 {len(other)}건 미합산")
            _put(ws, r, 2, cat)
            _put(ws, r, 3, len(ts))
            _put(ws, r, 7, _num_or_text(before) if before is not None else None)
            _put(ws, r, 8, _num_or_text(after) if after is not None else None)
            rate_cell = ws.cell(r, 9)
            rate_cell.value = (before - after) / before if before else None
            if before:
                rate_cell.number_format = "0.0%"
            _put(ws, r, 10, ", ".join(note) or None)
        return

    _resize_rows(ws, first, have, len(tasks))
    ws.cell(header, 3).value = "과제명"
    for i, t in enumerate(tasks):
        r = first + i
        for c, v in ((2, t.category), (3, t.title), (7, _num_or_text(t.before_val)),
                     (8, _num_or_text(t.after_val)), (9, t.effect), (10, t.unit)):
            _put(ws, r, c, v)
        fonts = (done_font or open_font) if t.done else (open_font or done_font)
        for c in range(FIRST_COL, LAST_COL + 1):
            f = fonts.get(c) or ws.cell(r, c).font
            if t.done and not done_font:  # template has no completed row to copy: recolor
                f = Font(name=f.name, size=f.size, bold=f.bold, italic=f.italic, color=BLUE)
            ws.cell(r, c).font = copy(f)


def _fill_summary(ws, note):
    m = _find_row(ws, lambda v: v.startswith("□ 금주 컨설팅 요약"))
    if not m:
        return
    for r in range(m + 1, m + 4):
        if _merge_span(ws, r, FIRST_COL) > 1 or ws.cell(r, FIRST_COL).value:
            ws.cell(r, FIRST_COL).value = (note or {}).get("summary")
            return


def _fill_activities(ws, tasks: list[TaskAt], note, year, week):
    note = note or {}
    r_now = _find_row(ws, lambda v: v.startswith("금주 내용"))
    if r_now:
        rd = note.get("report_date")
        stamp = f"{week}W,{date.fromisoformat(rd).month}/{date.fromisoformat(rd).day}" if rd else f"{week}W"
        ws.cell(r_now, FIRST_COL).value = f"금주 내용\n[{stamp}] "
        _put(ws, r_now, 3, note.get("common"))
        lines = [f"{i}.{t.title} : {t.week_content}"
                 for i, t in enumerate([t for t in tasks if t.week_content], start=1)]
        body = "\n".join(x for x in [note.get("detail"), "\n".join(lines)] if x) or None
        if _merge_span(ws, r_now, FIRST_COL) > 1:
            _put(ws, r_now + 1, 3, body)
            _set_lines_height(ws, r_now + 1, body)
    r_next = _find_row(ws, lambda v: v.startswith("차주 계획"))
    if r_next:
        ny, nw = next_week(year, week)
        vd = note.get("next_visit_date")
        stamp = f"{nw}W,{date.fromisoformat(vd).month}/{date.fromisoformat(vd).day}" if vd else f"{nw}W"
        ws.cell(r_next, FIRST_COL).value = f"차주 계획\n[{stamp}]"
        span = _merge_span(ws, r_next, FIRST_COL)
        visit = " ".join(x for x in [md_with_weekday(date.fromisoformat(vd)) if vd else None,
                                     note.get("next_visit_time")] if x)
        if span >= 4:
            _put(ws, r_next + 1, 3, f" - {visit}" if visit else None)
            _put(ws, r_next + 3, 3, note.get("next_plan"))
            _set_lines_height(ws, r_next + 3, note.get("next_plan"))


def fill_sheet(ws: Worksheet, conn, company, year: int, week: int, base_template: bool, warnings: list) -> None:
    tasks = tasks_at(conn, company["id"], year, week)
    note = get_note(conn, company["id"], year, week)
    if note is None:
        warnings.append(f"{week}주 주간 메모가 없어 컨설팅 요약·공통·차주 계획 칸이 비었습니다")
    _fill_activities(ws, tasks, note, year, week)
    _fill_summary(ws, note)
    _fill_kpi(ws, company, tasks, warnings)
    _fill_status_table(ws, tasks, base_template)
    _fill_overview(ws, company)
    _fill_title(ws, year, week)


# ---------- workbook ----------

def template_path(company_id: int):
    p = config.TEMPLATE_DIR / f"{company_id}.xlsx"
    return (p, False) if p.exists() else (config.TEMPLATE_DIR / "_base.xlsx", True)


def build(conn: sqlite3.Connection, company_id: int, year: int, week: int) -> Result:
    company = conn.execute("SELECT * FROM companies WHERE id=?", (company_id,)).fetchone()
    if company is None:
        raise LookupError("company not found")
    path, is_base = template_path(company_id)
    wb = openpyxl.load_workbook(path)
    warnings = []

    originals = {int(m.group(1)): ws for ws in wb.worksheets if (m := WEEK_SHEET.match(ws.title))}
    others = [ws for ws in wb.worksheets if not WEEK_SHEET.match(ws.title) and ws.title != "base"]
    proto = wb["base"] if is_base else originals[max(originals)]

    if is_base:
        created = week_of(date.fromisoformat(company["created_at"][:10]))
        start = created if week_monday(*created) <= week_monday(year, week) else (year, week)
        gen_weeks = weeks_between(start, (year, week))
    elif week > max(originals):
        gen_weeks = weeks_between(next_week(year, max(originals)), (year, week))
    else:
        gen_weeks = []

    generated = []
    for y, w in gen_weeks:
        ws = wb.copy_worksheet(proto)
        ws.title = f"{w}주"
        fill_sheet(ws, conn, company, y, w, is_base, warnings)
        generated.append(ws)

    kept = [ws for n, ws in sorted(originals.items(), reverse=True) if n <= week]
    order = list(reversed(generated)) + kept + others
    for ws in wb.worksheets:
        if ws not in order:
            wb.remove(ws)
    wb._sheets = order
    wb.active = 0
    for ws in order:
        ws.sheet_view.tabSelected = ws is order[0]

    note = get_note(conn, company_id, year, week) if generated else None
    stamp = date.fromisoformat(note["report_date"]) if note and note.get("report_date") else today_kst()
    filename = f"{week}W_{company['name']}_Feedback_Report_{stamp:%y%m%d}.xlsx"
    buf = io.BytesIO()
    wb.save(buf)
    return Result(buf.getvalue(), filename, [ws.title for ws in order], warnings)
